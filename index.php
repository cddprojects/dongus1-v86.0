  <section id="checklist" class="checklist">
    <div class="wrap">
      <p class="eyebrow">Before an application</p>
      <h2>What a listing usually includes</h2>
      <p class="lede">State, schedule, training, pay, employment type, and the employer. Those details let one listing sit beside another.</p>
      <ol class="steps">
        <li>
          <h3>State eligibility</h3>
          <p>The role is open in that state and time zone.</p>
        </li>
        <li>
          <h3>Schedule</h3>
          <p>Set shifts, core hours, or a deadline.</p>
        </li>
        <li>
          <h3>Training</h3>
          <p>Online onboarding, and the hours those sessions take.</p>
        </li>
        <li>
          <h3>Pay</h3>
          <p>The rate, how much work is offered, and the pay schedule.</p>
        </li>
        <li>
          <h3>Employment type</h3>
          <p>W-2 employee, 1099 contractor, or one task at a time.</p>
        </li>
        <li>
          <h3>Employer</h3>
          <p>A posting on the company’s careers page.</p>
        </li>
      </ol>
      <p class="aside-note">“Flexible” can still mean core hours or a scheduled shift.</p>
      <div class="walkaway">
        <h2>When to leave a listing alone</h2>
        <p class="lede">A posting can say work from home and still be the wrong place for an application.</p>
        <ul>
          <li>
            <h3>It asks for money</h3>
            <p>A fee, a starter kit, or payment for training is a warning sign.</p>
          </li>
          <li>
            <h3>The company is missing</h3>
            <p>The role is not on the employer’s own careers page.</p>
          </li>
          <li>
            <h3>The week is blank</h3>
            <p>No state, no hours, and no rate. “Flexible” is doing all the work.</p>
          </li>
        </ul>
      </div>
    </div>
  </section>

