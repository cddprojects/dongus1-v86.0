      <div class="pay-kinds">
        <article id="hourly">
          <h3>Hourly pay</h3>
          <p>At $18 an hour, 15 hours comes to $270. Those hours may not be guaranteed.</p>
        </article>
        <article id="project">
          <h3>Project pay</h3>
          <p>A $120 project comes to $30 an hour over four hours, or $20 over six, once messages and revisions are counted.</p>
        </article>
        <article id="task-pay">
          <h3>Task pay</h3>
          <p>A $10 user test depends on how long it takes and how often another one is available.</p>
        </article>
      </div>

      <div class="payday" id="payday">
